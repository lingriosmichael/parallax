"""PAX-A09: draws the in-game UI's line art into Assets/_Game/Art/UI/Game/, the title's gold language at play size (Tools/Art/title_ui.py makes the
plate and flourish these screens share). Everything is drawn here, nothing is generated by a paid service. The portrait is cut from the developer's
character sheet. Play controls keep a dark hairline around a pale line, so they read on the brightest sky and the darkest stone.

    python3 Tools/Art/game_ui.py      (numpy and Pillow)
"""
import os
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "Assets", "_Game", "Art", "UI", "Game")
SHEET = os.path.join(ROOT, "DesignImages", "13_cat-character-sheet.png")
SS = 4     # drawn this much larger, then reduced, for clean thin lines
GOLD = (255, 226, 160)
PALE = (255, 248, 232)
SHADOW = (20, 12, 6)


def canvas(w, h=None): return Image.new("L", (w * SS, (h or w) * SS), 0)


def save(mask, colour, name, under=None):
    """White-free line art: `colour` where the mask is, over an optional (colour, alpha array) ground."""
    size = (mask.width // SS, mask.height // SS)
    a = np.array(mask.resize(size, Image.LANCZOS)) / 255.0
    rgb = np.ones(a.shape + (3,)) * (np.array(colour) / 255.0)
    alpha = a
    if under is not None:
        ground, strength = under
        base = np.array(ground) / 255.0
        rgb = base * (1 - a[..., None]) + rgb * a[..., None]
        alpha = np.maximum(a, strength)
    rgba = np.dstack([rgb, alpha])
    Image.fromarray((rgba * 255).clip(0, 255).astype("uint8"), "RGBA").save(os.path.join(OUT, name))


def halo(mask, width):
    """The dark hairline: the line, widened, a little soft."""
    return mask.filter(ImageFilter.MaxFilter(width * SS * 2 + 1)).filter(ImageFilter.GaussianBlur(width * SS * 0.45))


def with_shadow(mask, colour, name, width=2, strength=0.55):
    size = (mask.width // SS, mask.height // SS)
    line = np.array(mask.resize(size, Image.LANCZOS)) / 255.0
    shade = np.array(halo(mask, width).resize(size, Image.LANCZOS)) / 255.0 * strength
    alpha = 1 - (1 - line) * (1 - shade)
    keep = np.maximum(alpha, 1e-3)[..., None]
    rgb = (np.array(colour) / 255.0 * line[..., None] + np.array(SHADOW) / 255.0 * (shade * (1 - line))[..., None]) / keep
    Image.fromarray((np.dstack([rgb, alpha]) * 255).clip(0, 255).astype("uint8"), "RGBA").save(os.path.join(OUT, name))


def disc_alpha(size, radius):
    y, x = np.mgrid[0:size, 0:size] + 0.5
    d = np.sqrt((x - size / 2) ** 2 + (y - size / 2) ** 2)
    return np.clip(radius - d + 0.5, 0, 1)


def ring(size=384):
    """Stick base, jump and pause: a double gold-white line around a faint dark glass."""
    img = canvas(size); d = ImageDraw.Draw(img); c = size * SS / 2
    r = c - 12 * SS
    d.ellipse([c - r, c - r, c + r, c + r], outline=255, width=4 * SS)
    r2 = r - 11 * SS
    for i in range(720):    # a hair inside it, broken, as the sigil's band is
        if i % 40 < 32:
            t = np.radians(i / 2); t2 = np.radians((i + 1) / 2)
            d.line([(c + r2 * np.cos(t), c + r2 * np.sin(t)), (c + r2 * np.cos(t2), c + r2 * np.sin(t2))], fill=120, width=SS)
    small = (size, size)
    line = np.array(img.resize(small, Image.LANCZOS)) / 255.0
    shade = np.array(halo(img, 2).resize(small, Image.LANCZOS)) / 255.0 * 0.6
    glass = disc_alpha(size, size / 2 - 12) * 0.2
    alpha = np.maximum(1 - (1 - line) * (1 - shade), glass)
    keep = np.maximum(alpha, 1e-3)[..., None]
    rgb = (np.array(PALE) / 255.0 * line[..., None] + np.array(SHADOW) / 255.0 * (alpha - line).clip(0, 1)[..., None]) / keep
    Image.fromarray((np.dstack([rgb, alpha]) * 255).clip(0, 255).astype("uint8"), "RGBA").save(os.path.join(OUT, "GUI_Ring.png"))


def knob(size=192):
    img = canvas(size); d = ImageDraw.Draw(img); c = size * SS / 2
    r = c - 10 * SS
    d.ellipse([c - r, c - r, c + r, c + r], outline=255, width=4 * SS)
    r3 = r * 0.2
    d.polygon([(c - r3, c), (c, c - r3 * 1.5), (c + r3, c), (c, c + r3 * 1.5)], fill=255)
    small = (size, size)
    line = np.array(img.resize(small, Image.LANCZOS)) / 255.0
    glass = disc_alpha(size, size / 2 - 10) * 0.42
    alpha = np.maximum(line, glass)
    keep = np.maximum(alpha, 1e-3)[..., None]
    rgb = (np.array(PALE) / 255.0 * line[..., None] + np.array(SHADOW) / 255.0 * (alpha - line).clip(0, 1)[..., None]) / keep
    Image.fromarray((np.dstack([rgb, alpha]) * 255).clip(0, 255).astype("uint8"), "RGBA").save(os.path.join(OUT, "GUI_Knob.png"))


def chevron(size=192):
    img = canvas(size); d = ImageDraw.Draw(img); s = size * SS
    pts = [(s * 0.2, s * 0.66), (s * 0.5, s * 0.34), (s * 0.8, s * 0.66)]
    d.line(pts, fill=255, width=9 * SS, joint="curve")
    with_shadow(img, PALE, "GUI_Chevron.png", 3)


def pause(size=128):
    img = canvas(size); d = ImageDraw.Draw(img); s = size * SS
    for x in (0.36, 0.64):
        d.rounded_rectangle([s * x - 6 * SS, s * 0.26, s * x + 6 * SS, s * 0.74], radius=3 * SS, fill=255)
    with_shadow(img, PALE, "GUI_Pause.png", 3)


def lock(size=128):
    img = canvas(size); d = ImageDraw.Draw(img); s = size * SS
    w = 7 * SS
    d.arc([s * 0.31, s * 0.14, s * 0.69, s * 0.62], 180, 360, fill=255, width=w)
    d.line([(s * 0.31 + w / 2, s * 0.38), (s * 0.31 + w / 2, s * 0.5)], fill=255, width=w)
    d.line([(s * 0.69 - w / 2, s * 0.38), (s * 0.69 - w / 2, s * 0.5)], fill=255, width=w)
    d.rounded_rectangle([s * 0.2, s * 0.46, s * 0.8, s * 0.88], radius=7 * SS, fill=255)
    c, y = s * 0.5, s * 0.65
    keyhole = 4 * SS
    d.ellipse([c - keyhole * 1.3, y - keyhole * 1.8, c + keyhole * 1.3, y + keyhole * 0.8], fill=0)
    d.polygon([(c - keyhole * 0.7, y), (c + keyhole * 0.7, y), (c + keyhole, y + keyhole * 2.4), (c - keyhole, y + keyhole * 2.4)], fill=0)
    save(img, (255, 255, 255), "GUI_Lock.png")


def diamond(size=64):
    """The flourish's diamond: the done mark on a cell, a section on the progress line, and the door at its end."""
    img = canvas(size); d = ImageDraw.Draw(img); c = size * SS / 2; r = c * 0.86
    d.polygon([(c - r * 0.72, c), (c, c - r), (c + r * 0.72, c), (c, c + r)], fill=255)
    save(img, (255, 255, 255), "GUI_Diamond.png")


def dot(size=64):
    img = canvas(size); d = ImageDraw.Draw(img); c = size * SS / 2; r = c * 0.82
    d.ellipse([c - r, c - r, c + r, c + r], fill=255)
    save(img, (255, 255, 255), "GUI_Dot.png")


def bar(w=8, h=8):
    Image.new("RGBA", (w, h), (255, 255, 255, 255)).save(os.path.join(OUT, "GUI_Bar.png"))


def portrait(size=256):
    """Cat A's front view from the character sheet, in a disc on its own warm paper. The sheet's head is small, so it's enlarged, then graded a
    little warmer and darker around the edge so the ring has a ground to sit on."""
    sheet = Image.open(SHEET).convert("RGB")
    cx, cy, half = 632, 362, 62
    crop = sheet.crop((cx - half, cy - half, cx + half, cy + half)).resize((size, size), Image.LANCZOS).filter(ImageFilter.UnsharpMask(3, 60, 2))
    rgb = np.array(crop) / 255.0
    y, x = np.mgrid[-1:1:size * 1j, -1:1:size * 1j]
    d = np.sqrt(x * x + y * y)
    shade = 1 - np.clip((d - 0.45) / 0.55, 0, 1) ** 2 * 0.5
    rgb = rgb * shade[..., None] * np.array([1.0, 0.93, 0.82])
    alpha = disc_alpha(size, size / 2 - 3)
    Image.fromarray((np.dstack([rgb, alpha]) * 255).clip(0, 255).astype("uint8"), "RGBA").save(os.path.join(OUT, "GUI_Portrait.png"))


def chamfered(w, h, inset, cut):
    return [(inset + cut, inset), (w - inset - cut, inset), (w - inset, inset + cut), (w - inset, h - inset - cut),
            (w - inset - cut, h - inset), (inset + cut, h - inset), (inset, h - inset - cut), (inset, inset + cut)]


def panel(w=512, h=180):
    """The title's plate with a solid ground, for a panel over busy art: nothing under it may read through its type. Stretched by its corners."""
    fill = Image.new("L", (w * SS, h * SS), 0)
    ImageDraw.Draw(fill).polygon(chamfered(w * SS, h * SS, 4 * SS, 22 * SS), fill=255)
    line = canvas(w, h); d = ImageDraw.Draw(line)
    pts = chamfered(w * SS, h * SS, 4 * SS, 22 * SS); d.line(pts + pts[:2], fill=255, width=3 * SS, joint="curve")
    pts = chamfered(w * SS, h * SS, 13 * SS, 26 * SS); d.line(pts + pts[:2], fill=120, width=1 * SS, joint="curve")
    fill = np.array(fill.resize((w, h), Image.LANCZOS)) / 255.0
    line = np.array(line.resize((w, h), Image.LANCZOS)) / 255.0
    dark = np.ones((h, w, 3)) * np.array([0.1, 0.062, 0.032])
    gold = np.ones((h, w, 3)) * np.array([0.96, 0.76, 0.42])
    rgb = dark * (1 - line[..., None]) + gold * line[..., None]
    Image.fromarray((np.dstack([rgb, np.maximum(fill, line)]) * 255).clip(0, 255).astype("uint8"), "RGBA").save(os.path.join(OUT, "GUI_Panel.png"))


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    ring(); knob(); chevron(); pause(); lock(); diamond(); dot(); bar(); portrait(); panel()
    for f in sorted(os.listdir(OUT)):
        if f.endswith(".png"): print(f, Image.open(os.path.join(OUT, f)).size)
